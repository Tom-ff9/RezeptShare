begin;

create schema if not exists private;

create table public.profile (
    id uuid primary key references auth.users(id) on delete cascade,
    anzeigename text not null check (char_length(btrim(anzeigename)) between 1 and 60),
    erstellt_am timestamptz not null default now()
);

create table public.gruppen (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(btrim(name)) between 1 and 80),
    ist_persoenlich boolean not null default false,
    erstellt_von uuid not null references public.profile(id) on delete restrict,
    erstellt_am timestamptz not null default now()
);

create table public.gruppen_mitglieder (
    gruppen_id bigint not null,
    benutzer_id uuid not null,
    rolle text not null check (rolle in ('besitzer', 'mitglied')),
    beigetreten_am timestamptz not null default now(),
    constraint gruppen_mitglieder_pkey primary key (gruppen_id, benutzer_id),
    constraint gruppen_mitglieder_gruppen_id_fkey foreign key (gruppen_id)
        references public.gruppen(id) on delete cascade,
    constraint gruppen_mitglieder_benutzer_id_fkey foreign key (benutzer_id)
        references public.profile(id) on delete cascade
);

create table public.rezepte (
    id bigint generated by default as identity primary key,
    gruppen_id bigint not null,
    erstellt_von uuid not null,
    name text not null check (char_length(btrim(name)) between 1 and 120),
    text text not null check (char_length(btrim(text)) between 1 and 20000),
    bild_pfad text,
    kalorien numeric check (kalorien is null or kalorien >= 0),
    protein numeric check (protein is null or protein >= 0),
    kohlenhydrate numeric check (kohlenhydrate is null or kohlenhydrate >= 0),
    fett numeric check (fett is null or fett >= 0),
    erstellt_am timestamptz not null default now(),
    aktualisiert_am timestamptz not null default now(),
    constraint rezepte_gruppen_id_fkey foreign key (gruppen_id)
        references public.gruppen(id) on delete cascade,
    constraint rezepte_erstellt_von_fkey foreign key (erstellt_von)
        references public.profile(id) on delete restrict
);

create table public.einladungen (
    id bigint generated by default as identity primary key,
    gruppen_id bigint not null references public.gruppen(id) on delete cascade,
    email text not null,
    token uuid not null unique default gen_random_uuid(),
    erstellt_von uuid not null references public.profile(id) on delete cascade,
    erstellt_am timestamptz not null default now(),
    gueltig_bis timestamptz not null,
    angenommen_am timestamptz
);

create index idx_gruppen_mitglieder_benutzer
    on public.gruppen_mitglieder (benutzer_id, gruppen_id);
create index idx_rezepte_gruppe_aktualisiert
    on public.rezepte (gruppen_id, aktualisiert_am desc);
create index idx_einladungen_gruppe_email
    on public.einladungen (gruppen_id, lower(email));

-- Diese Hilfsfunktionen vermeiden rekursive RLS-Prüfungen bei Mitgliedschaften.
create or replace function private.ist_gruppenmitglied(p_gruppen_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select (select auth.uid()) is not null and exists (
        select 1
        from public.gruppen_mitglieder
        where gruppen_id = p_gruppen_id
          and benutzer_id = (select auth.uid())
    );
$$;

create or replace function private.ist_gruppenbesitzer(p_gruppen_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select (select auth.uid()) is not null and exists (
        select 1
        from public.gruppen_mitglieder
        where gruppen_id = p_gruppen_id
          and benutzer_id = (select auth.uid())
          and rolle = 'besitzer'
    );
$$;

create or replace function private.darf_profil_sehen(p_profil_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select (select auth.uid()) = p_profil_id or exists (
        select 1
        from public.gruppen_mitglieder eigenes
        join public.gruppen_mitglieder anderes
          on anderes.gruppen_id = eigenes.gruppen_id
        where eigenes.benutzer_id = (select auth.uid())
          and anderes.benutzer_id = p_profil_id
    );
$$;

create or replace function private.gruppen_id_aus_bildpfad(p_pfad text)
returns bigint
language sql
immutable
set search_path = ''
as $$
    select case
        when p_pfad ~ '^[0-9]+/' then split_part(p_pfad, '/', 1)::bigint
        else null
    end;
$$;

create or replace function private.aktualisiert_am_setzen()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.aktualisiert_am = now();
    return new;
end;
$$;

create or replace function private.rezept_zuordnung_schuetzen()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if new.erstellt_von <> old.erstellt_von or new.gruppen_id <> old.gruppen_id then
        raise exception 'Ersteller und Gruppe eines Rezepts dürfen nicht geändert werden.';
    end if;
    return new;
end;
$$;

create trigger rezepte_aktualisiert_am
before update on public.rezepte
for each row execute function private.aktualisiert_am_setzen();

create trigger rezept_zuordnung_schuetzen
before update on public.rezepte
for each row execute function private.rezept_zuordnung_schuetzen();

-- Registrierung, Profil und persönliche Gruppe entstehen in einer Transaktion.
create or replace function private.neuen_benutzer_vorbereiten()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_anzeigename text;
    v_gruppen_id bigint;
begin
    v_anzeigename := left(
        coalesce(
            nullif(btrim(new.raw_user_meta_data ->> 'anzeigename'), ''),
            nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
            'Familienmitglied'
        ),
        60
    );

    insert into public.profile (id, anzeigename)
    values (new.id, v_anzeigename);

    insert into public.gruppen (name, ist_persoenlich, erstellt_von)
    values ('Meine Rezepte', true, new.id)
    returning id into v_gruppen_id;

    insert into public.gruppen_mitglieder (gruppen_id, benutzer_id, rolle)
    values (v_gruppen_id, new.id, 'besitzer');

    return new;
end;
$$;

drop trigger if exists benutzer_nach_registrierung on auth.users;
create trigger benutzer_nach_registrierung
after insert on auth.users
for each row execute function private.neuen_benutzer_vorbereiten();

