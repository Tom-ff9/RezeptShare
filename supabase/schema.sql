create function public.rezept_speichern_intern(p_person uuid, p_id bigint, p_version integer, p_daten jsonb, p_markierungen jsonb)
returns integer language plpgsql security definer set search_path = '' as $$
declare r public.rezepte; v_gruppe bigint; v_version integer;
begin
 select gruppen_id into v_gruppe from public.rezepte where id=p_id;
 perform 1 from public.profile where id=p_person and not wird_geloescht for share;
 if not found then raise exception 'Das Konto ist nicht aktiv.'; end if;
 perform 1 from public.gruppen where id=v_gruppe for update;
 select * into r from public.rezepte where id=p_id for update;
 if not found or not private.darf_schreiben(v_gruppe,p_person) then raise exception 'Keine Bearbeitungsrechte.'; end if;
 if r.version<>p_version then raise exception 'Das Rezept wurde inzwischen geändert. Bitte lade es neu und übernimm deine Änderungen erneut.'; end if;
 if (p_daten->>'bild_pfad') is not null and not exists(select 1 from storage.objects where bucket_id='rezeptbilder' and name=p_daten->>'bild_pfad'
 and private.gruppen_id_aus_bildpfad(name)=r.gruppen_id) then raise exception 'Ungültiges Rezeptbild.'; end if;
 update public.rezepte set name=p_daten->>'name', text=p_daten->>'text', bild_pfad=p_daten->>'bild_pfad',
 kalorien=(p_daten->>'kalorien')::numeric, protein=(p_daten->>'protein')::numeric,
 kohlenhydrate=(p_daten->>'kohlenhydrate')::numeric, fett=(p_daten->>'fett')::numeric, version=version+1
 where id=p_id returning version into v_version;
 -- Behaltene IDs bewahren persönliche Ausblendungen. Überlagerte Hinweise entfallen.
 delete from public.rezept_aenderungen a where a.rezept_id=p_id and not exists
 (select 1 from jsonb_array_elements(p_markierungen) m where (m->>'id')::uuid=a.id);
 insert into public.rezept_aenderungen(id,rezept_id,feld,start_pos,ende_pos,bereiche,alter_text,autor_id,erstellt_am,ablauf_am)
 select (m->>'id')::uuid,p_id,m->>'feld',(m->>'start_pos')::int,(m->>'ende_pos')::int,m->'bereiche',coalesce(m->>'alter_text',''),
 (m->>'autor_id')::uuid,coalesce((m->>'erstellt_am')::timestamptz,now()),coalesce((m->>'ablauf_am')::timestamptz,now()+interval '1 month')
 from jsonb_array_elements(p_markierungen) m
 on conflict(id) do update set start_pos=excluded.start_pos,ende_pos=excluded.ende_pos,bereiche=excluded.bereiche;
 return v_version;
end; $$;

