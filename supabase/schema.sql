create or replace function public.gruppe_erstellen(p_name text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_benutzer_id uuid := auth.uid();
    v_name text := btrim(coalesce(p_name, ''));
    v_gruppen_id bigint;
begin
    if v_benutzer_id is null then
        raise exception 'Bitte melde dich zuerst an.';
    end if;
    if char_length(v_name) < 1 or char_length(v_name) > 80 then
        raise exception 'Bitte gib einen Gruppennamen mit höchstens 80 Zeichen ein.';
    end if;

    insert into public.gruppen (name, ist_persoenlich, erstellt_von)
    values (v_name, false, v_benutzer_id)
    returning id into v_gruppen_id;

    insert into public.gruppen_mitglieder (gruppen_id, benutzer_id, rolle)
    values (v_gruppen_id, v_benutzer_id, 'besitzer');

    return v_gruppen_id;
end;
$$;

create or replace function public.gruppen_auflisten()
returns table (
    id bigint,
    name text,
    ist_persoenlich boolean,
    rolle text,
    mitglieder_anzahl bigint,
    rezepte_anzahl bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
    select
        g.id,
        g.name,
        g.ist_persoenlich,
        gm.rolle,
        (select count(*) from public.gruppen_mitglieder alle where alle.gruppen_id = g.id),
        (select count(*) from public.rezepte r where r.gruppen_id = g.id)
    from public.gruppen_mitglieder gm
    join public.gruppen g on g.id = gm.gruppen_id
    where gm.benutzer_id = (select auth.uid())
    order by g.ist_persoenlich desc, lower(g.name);
$$;

create or replace function public.einladung_erstellen(
    p_gruppen_id bigint,
    p_email text
)
returns table (token uuid, gueltig_bis timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_benutzer_id uuid := auth.uid();
    v_email text := lower(btrim(coalesce(p_email, '')));
    v_token uuid := gen_random_uuid();
    v_gueltig_bis timestamptz := now() + interval '7 days';
    v_ist_persoenlich boolean;
begin
    if v_benutzer_id is null then
        raise exception 'Bitte melde dich zuerst an.';
    end if;
    if not private.ist_gruppenbesitzer(p_gruppen_id) then
        raise exception 'Nur der Gruppenbesitzer kann Personen einladen.';
    end if;

    select g.ist_persoenlich into v_ist_persoenlich
    from public.gruppen g where g.id = p_gruppen_id;

    if v_ist_persoenlich then
        raise exception 'Die Gruppe „Meine Rezepte“ ist privat.';
    end if;
    if v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
        raise exception 'Bitte gib eine gültige E-Mail-Adresse ein.';
    end if;
    if exists (
        select 1
        from public.gruppen_mitglieder gm
        join auth.users u on u.id = gm.benutzer_id
        where gm.gruppen_id = p_gruppen_id
          and lower(u.email) = v_email
    ) then
        raise exception 'Diese Person ist bereits Mitglied der Gruppe.';
    end if;

    delete from public.einladungen
    where gruppen_id = p_gruppen_id
      and lower(email) = v_email
      and angenommen_am is null;

    insert into public.einladungen (
        gruppen_id, email, token, erstellt_von, gueltig_bis
    ) values (
        p_gruppen_id, v_email, v_token, v_benutzer_id, v_gueltig_bis
    );

    return query select v_token, v_gueltig_bis;
end;
$$;

create or replace function public.einladung_annehmen(p_token uuid)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_benutzer_id uuid := auth.uid();
    v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
    v_einladung public.einladungen%rowtype;
begin
    if v_benutzer_id is null then
        raise exception 'Bitte melde dich zuerst an.';
    end if;

    select * into v_einladung
    from public.einladungen
    where token = p_token
    for update;

    if not found or v_einladung.angenommen_am is not null or v_einladung.gueltig_bis < now() then
        raise exception 'Diese Einladung ist ungültig oder abgelaufen.';
    end if;
    if lower(v_einladung.email) <> v_email then
        raise exception 'Die Einladung wurde für eine andere E-Mail-Adresse erstellt.';
    end if;

    insert into public.gruppen_mitglieder (gruppen_id, benutzer_id, rolle)
    values (v_einladung.gruppen_id, v_benutzer_id, 'mitglied')
    on conflict (gruppen_id, benutzer_id) do nothing;

    update public.einladungen
    set angenommen_am = now()
    where id = v_einladung.id;

    return v_einladung.gruppen_id;
end;
$$;

