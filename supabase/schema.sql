create or replace function public.einladung_annehmen(p_token uuid)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_benutzer_id uuid := auth.uid();
    v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
    v_einladung public.einladungen%rowtype;
begin
    if not private.konto_aktiv(v_benutzer_id) then
        raise exception 'Bitte melde dich zuerst an.';
    end if;

    select * into v_einladung
    from public.einladungen
    where token = p_token
    for update;

    if not found or v_einladung.angenommen_am is not null or v_einladung.gueltig_bis < now() then
        raise exception 'Diese Einladung ist ungültig oder abgelaufen.';
    end if;
    if lower(v_einladung.email) <> v_email then
        raise exception 'Die Einladung wurde für eine andere E-Mail-Adresse erstellt.';
    end if;

    perform 1 from public.gruppen where id = v_einladung.gruppen_id for update;
    if not exists (select 1 from public.gruppen_mitglieder gm join public.profile p on p.id=gm.benutzer_id
        where gm.gruppen_id=v_einladung.gruppen_id and gm.rolle='admin' and not p.wird_geloescht) then
        raise exception 'Diese Gruppe wird gelöscht und nimmt keine neuen Personen auf.';
    end if;
    insert into public.gruppen_mitglieder (gruppen_id, benutzer_id, rolle)
    select v_einladung.gruppen_id, v_benutzer_id, case when g.neue_nur_ansehen then 'beobachter' else 'mitglied' end from public.gruppen g where g.id=v_einladung.gruppen_id
    on conflict (gruppen_id, benutzer_id) do nothing;

    update public.einladungen
    set angenommen_am = now()
    where id = v_einladung.id;

    return v_einladung.gruppen_id;
end;
$$;

