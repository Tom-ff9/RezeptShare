async function asUser(i, query, params=[]) {
    await db.exec('reset role');
    await db.query(`select set_config('request.jwt.claim.sub',$1,false),set_config('request.jwt.claims',$2,false)`,[ids[i],JSON.stringify({email:`p${i}@test.invalid`})]);
    await db.exec('set role authenticated');
    try { return await db.query(query,params); }
    finally { await db.exec('reset role'); await db.exec(`select set_config('request.jwt.claim.sub','',false)`); }
}
